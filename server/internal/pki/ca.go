// Package pki is the IAF-internal certificate authority. The CA private key
// is an ECDSA P-384 key resident in the HSM (PKCS#11); only the certificate
// is stored outside it. The CA issues:
//   - X.509-SVID workload certificates (SPIFFE ID in the URI SAN) used for
//     mTLS between mesh services, and
//   - device certificates binding an enrolled device's hardware-held key.
package pki

import (
	"crypto"
	"crypto/ecdsa"
	"crypto/rand"
	"crypto/sha256"
	"crypto/tls"
	"crypto/x509"
	"crypto/x509/pkix"
	"encoding/hex"
	"encoding/pem"
	"errors"
	"fmt"
	"math/big"
	"net"
	"net/url"
	"os"
	"strings"
	"time"
)

// TrustDomain is the SPIFFE trust domain of the deployment.
const TrustDomain = "siepmu.iaf"

type CA struct {
	Cert   *x509.Certificate
	signer crypto.Signer
}

// NewRootCA creates a self-signed root certificate for an HSM-resident key.
func NewRootCA(signer crypto.Signer, commonName string, validity time.Duration) (*CA, error) {
	serial, err := randSerial()
	if err != nil {
		return nil, err
	}
	pub := signer.Public()
	ski := keyID(pub)
	tmpl := &x509.Certificate{
		SerialNumber:          serial,
		Subject:               pkix.Name{CommonName: commonName, Organization: []string{"SIEPMU-SX"}},
		NotBefore:             time.Now().Add(-time.Minute),
		NotAfter:              time.Now().Add(validity),
		KeyUsage:              x509.KeyUsageCertSign | x509.KeyUsageCRLSign | x509.KeyUsageDigitalSignature,
		BasicConstraintsValid: true,
		IsCA:                  true,
		MaxPathLenZero:        true,
		SubjectKeyId:          ski,
		URIs:                  []*url.URL{{Scheme: "spiffe", Host: TrustDomain}},
	}
	der, err := x509.CreateCertificate(rand.Reader, tmpl, tmpl, pub, signer)
	if err != nil {
		return nil, fmt.Errorf("pki: self-sign root: %w", err)
	}
	cert, err := x509.ParseCertificate(der)
	if err != nil {
		return nil, err
	}
	return &CA{Cert: cert, signer: signer}, nil
}

// LoadCA pairs a stored certificate with its HSM key, checking they match.
func LoadCA(certPEM []byte, signer crypto.Signer) (*CA, error) {
	b, _ := pem.Decode(certPEM)
	if b == nil {
		return nil, errors.New("pki: CA certificate is not PEM")
	}
	cert, err := x509.ParseCertificate(b.Bytes)
	if err != nil {
		return nil, err
	}
	cp, ok := cert.PublicKey.(*ecdsa.PublicKey)
	sp, ok2 := signer.Public().(*ecdsa.PublicKey)
	if !ok || !ok2 || !cp.Equal(sp) {
		return nil, errors.New("pki: CA certificate does not match HSM key")
	}
	return &CA{Cert: cert, signer: signer}, nil
}

func (c *CA) CertPEM() []byte {
	return pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: c.Cert.Raw})
}

func (c *CA) Pool() *x509.CertPool {
	p := x509.NewCertPool()
	p.AddCert(c.Cert)
	return p
}

// SPIFFEID builds spiffe://siepmu.iaf/<path>.
func SPIFFEID(path string) *url.URL {
	return &url.URL{Scheme: "spiffe", Host: TrustDomain, Path: "/" + strings.TrimPrefix(path, "/")}
}

// IssueWorkload issues a short-lived X.509-SVID for a mesh service. The leaf
// key is generated by the caller (it lives with the workload, not the CA).
func (c *CA) IssueWorkload(pub crypto.PublicKey, spiffePath string, dnsNames []string, ips []net.IP, ttl time.Duration) ([]byte, error) {
	serial, err := randSerial()
	if err != nil {
		return nil, err
	}
	id := SPIFFEID(spiffePath)
	tmpl := &x509.Certificate{
		SerialNumber:   serial,
		Subject:        pkix.Name{CommonName: id.String(), Organization: []string{"SIEPMU-SX workload"}},
		NotBefore:      time.Now().Add(-time.Minute),
		NotAfter:       time.Now().Add(ttl),
		KeyUsage:       x509.KeyUsageDigitalSignature | x509.KeyUsageKeyEncipherment,
		ExtKeyUsage:    []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth, x509.ExtKeyUsageClientAuth},
		URIs:           []*url.URL{id},
		DNSNames:       dnsNames,
		IPAddresses:    ips,
		AuthorityKeyId: c.Cert.SubjectKeyId,
		SubjectKeyId:   keyID(pub),
	}
	return x509.CreateCertificate(rand.Reader, tmpl, c.Cert, pub, c.signer)
}

// DeviceAttributes are embedded into a device certificate.
type DeviceAttributes struct {
	DeviceID      string
	ServiceNumber string
	Platform      string
}

// IssueDevice binds a device's hardware-held public key to its identity.
func (c *CA) IssueDevice(pub crypto.PublicKey, a DeviceAttributes, ttl time.Duration) (*x509.Certificate, error) {
	serial, err := randSerial()
	if err != nil {
		return nil, err
	}
	tmpl := &x509.Certificate{
		SerialNumber: serial,
		Subject: pkix.Name{
			CommonName:         a.DeviceID,
			SerialNumber:       a.ServiceNumber,
			OrganizationalUnit: []string{a.Platform},
			Organization:       []string{"SIEPMU-SX device"},
		},
		NotBefore:      time.Now().Add(-time.Minute),
		NotAfter:       time.Now().Add(ttl),
		KeyUsage:       x509.KeyUsageDigitalSignature,
		ExtKeyUsage:    []x509.ExtKeyUsage{x509.ExtKeyUsageClientAuth},
		URIs:           []*url.URL{SPIFFEID("device/" + a.DeviceID)},
		AuthorityKeyId: c.Cert.SubjectKeyId,
	}
	der, err := x509.CreateCertificate(rand.Reader, tmpl, c.Cert, pub, c.signer)
	if err != nil {
		return nil, err
	}
	return x509.ParseCertificate(der)
}

// WorkloadIdentity returns the SPIFFE ID path of a verified peer certificate.
func WorkloadIdentity(cert *x509.Certificate) (string, error) {
	for _, u := range cert.URIs {
		if u.Scheme == "spiffe" && u.Host == TrustDomain {
			return strings.TrimPrefix(u.Path, "/"), nil
		}
	}
	return "", errors.New("pki: certificate carries no SPIFFE ID in trust domain " + TrustDomain)
}

// ServerTLS returns a TLS 1.3 config preferring the hybrid post-quantum key
// exchange X25519MLKEM768. When clientCAs is non-nil client certificates are
// requested (smart-card / workload mTLS) and verified against it.
func ServerTLS(cert tls.Certificate, clientCAs *x509.CertPool, requireClient bool) *tls.Config {
	cfg := &tls.Config{
		MinVersion:       tls.VersionTLS13,
		Certificates:     []tls.Certificate{cert},
		CurvePreferences: []tls.CurveID{tls.X25519MLKEM768, tls.X25519},
	}
	if clientCAs != nil {
		cfg.ClientCAs = clientCAs
		if requireClient {
			cfg.ClientAuth = tls.RequireAndVerifyClientCert
		} else {
			cfg.ClientAuth = tls.VerifyClientCertIfGiven
		}
	}
	return cfg
}

// ClientTLS returns an mTLS client config that pins the internal CA and
// requires the server to present the expected SPIFFE ID.
func ClientTLS(cert tls.Certificate, roots *x509.CertPool, expectServerID string) *tls.Config {
	return &tls.Config{
		MinVersion:       tls.VersionTLS13,
		Certificates:     []tls.Certificate{cert},
		RootCAs:          roots,
		CurvePreferences: []tls.CurveID{tls.X25519MLKEM768, tls.X25519},
		// Hostname checks are replaced by SPIFFE ID checks.
		InsecureSkipVerify: true,
		VerifyPeerCertificate: func(raw [][]byte, _ [][]*x509.Certificate) error {
			if len(raw) == 0 {
				return errors.New("pki: server sent no certificate")
			}
			leaf, err := x509.ParseCertificate(raw[0])
			if err != nil {
				return err
			}
			inter := x509.NewCertPool()
			for _, r := range raw[1:] {
				if c, err := x509.ParseCertificate(r); err == nil {
					inter.AddCert(c)
				}
			}
			if _, err := leaf.Verify(x509.VerifyOptions{Roots: roots, Intermediates: inter, KeyUsages: []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth}}); err != nil {
				return fmt.Errorf("pki: server certificate: %w", err)
			}
			id, err := WorkloadIdentity(leaf)
			if err != nil {
				return err
			}
			if expectServerID != "" && id != expectServerID {
				return fmt.Errorf("pki: server identity %q, expected %q", id, expectServerID)
			}
			return nil
		},
	}
}

// WriteKeyPairPEM stores a workload certificate and its private key.
func WriteKeyPairPEM(certPath, keyPath string, certDER []byte, key crypto.PrivateKey) error {
	kd, err := x509.MarshalPKCS8PrivateKey(key)
	if err != nil {
		return err
	}
	if err := os.WriteFile(certPath, pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: certDER}), 0o644); err != nil {
		return err
	}
	return os.WriteFile(keyPath, pem.EncodeToMemory(&pem.Block{Type: "PRIVATE KEY", Bytes: kd}), 0o600)
}

// Fingerprint is the hex SHA-256 of a certificate.
func Fingerprint(cert *x509.Certificate) string {
	h := sha256.Sum256(cert.Raw)
	return hex.EncodeToString(h[:])
}

func randSerial() (*big.Int, error) {
	return rand.Int(rand.Reader, new(big.Int).Lsh(big.NewInt(1), 127))
}

func keyID(pub crypto.PublicKey) []byte {
	der, err := x509.MarshalPKIXPublicKey(pub)
	if err != nil {
		return nil
	}
	h := sha256.Sum256(der)
	return h[:20]
}
